import glob
import warnings
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.animation as animation
from scipy.ndimage import gaussian_filter
from astropy.io import fits
from astropy.wcs import WCS, FITSFixedWarning
from astropy.time import Time, TimeDelta
from astropy.stats import sigma_clipped_stats
from astropy.visualization import ImageNormalize, ZScaleInterval, LinearStretch
from astroquery.jplhorizons import Horizons
from reproject import reproject_interp

warnings.filterwarnings("ignore", category=FITSFixedWarning)
warnings.filterwarnings("ignore")

# -------------------------------------------------------------------------
# 1. Local Flux-Weighted Centroid Refinement
# -------------------------------------------------------------------------
def refine_centroid(data, x_approx, y_approx, rad=4.0, box=20, max_shift=4.0, sm=1.5):
    """Refines target position around an initial pixel coordinate estimate."""
    x0, y0 = x_approx - 1.0, y_approx - 1.0
    ix, iy = int(round(x0)), int(round(y0))
    
    # Boundary check
    if ix - box < 0 or ix + box + 1 > data.shape[1] or iy - box < 0 or iy + box + 1 > data.shape[0]:
        return x_approx, y_approx

    sub = data[iy - box : iy + box + 1, ix - box : ix + box + 1]
    yy, xx = np.mgrid[iy - box : iy + box + 1, ix - box : ix + box + 1]
    r = np.hypot(xx - x0, yy - y0)
    
    _, bkg, noise = sigma_clipped_stats(sub[(r > 10) & (r < box)], sigma=3)
    s = gaussian_filter(sub - bkg, sm)
    k = np.argmax(np.where(r <= max_shift, s, -np.inf))
    cx, cy = xx.flat[k], yy.flat[k]
    
    for _ in range(15):
        m = np.hypot(xx - cx, yy - cy) <= rad
        w = np.clip(sub - bkg, 0, None) * m
        if w.sum() <= 0:
            break
        ncx, ncy = (w * xx).sum() / w.sum(), (w * yy).sum() / w.sum()
        if np.hypot(ncx - cx, ncy - cy) < 1e-3:
            break
        cx, cy = ncx, ncy
        
    return cx + 1.0, cy + 1.0

# -------------------------------------------------------------------------
# 2. Extract Timing & Query JPL Horizons Ephemeris
# -------------------------------------------------------------------------
files = sorted(glob.glob("*.fits.gz"))
if not files:
    raise FileNotFoundError("No .fits.gz files found in the current directory.")

print(f"Processing {len(files)} FITS files...")
t_mid_jd = []
t_mid_isot = []
wcs_list = []
raw_headers = []

for f in files:
    with fits.open(f) as hdul:
        hdr = hdul[0].header
        raw_headers.append(hdr)
        t0 = Time(hdr["DATE-OBS"], scale="utc")
        tmid = t0 + TimeDelta(hdr["EXPTIME"] / 2.0, format="sec")
        t_mid_jd.append(tmid.jd)
        t_mid_isot.append(tmid.isot)
        wcs_list.append(WCS(hdr))

# Query JPL Horizons for 2005 QN173 (ID 248370) at GIT observatory site N50
print("Querying JPL Horizons ephemerides...")
eph = Horizons(id="248370", id_type="smallbody", location="N50", epochs=t_mid_jd).ephemerides()

# -------------------------------------------------------------------------
# 3. Centroid Target in Each Frame & Derive Celestial Trajectory
# -------------------------------------------------------------------------
ra_measured = []
dec_measured = []

print("Centroiding asteroid in each frame...")
for idx, (f, w, row) in enumerate(zip(files, wcs_list, eph)):
    with fits.open(f) as hdul:
        data = hdul[0].data.astype(np.float32)

    # Initial pixel location from ephemeris (1-indexed for WCS)
    x_pred, y_pred = w.all_world2pix(row["RA"], row["DEC"], 1)

    # Refine centroid on the source
    cx, cy = refine_centroid(data, x_pred, y_pred)

    # Convert refined centroid back to RA / Dec
    ra_ref, dec_ref = (float(v) for v in w.all_pix2world(cx, cy, 1))
    ra_measured.append(ra_ref)
    dec_measured.append(dec_ref)
    print(f"[{idx+1:02d}/{len(files)}] {f} -> (x={cx:.2f}, y={cy:.2f}) | RA={ra_ref:.6f}, Dec={dec_ref:.6f}")

ra_measured = np.array(ra_measured)
dec_measured = np.array(dec_measured)
jds = np.array(t_mid_jd)

# -------------------------------------------------------------------------
# 4. Construct Common Celestial Canvas
# -------------------------------------------------------------------------
ra_center = np.mean(ra_measured)
dec_center = np.mean(dec_measured)
COMMON_SIZE = (1800, 1800)  # (ny, nx)
pixel_scale_deg = 0.675 / 3600.0  # Native scale ~0.675 arcsec/px

ref_header = fits.Header()
ref_header["NAXIS"] = 2
ref_header["NAXIS1"] = COMMON_SIZE[1]
ref_header["NAXIS2"] = COMMON_SIZE[0]
ref_header["CTYPE1"] = "RA---TAN"
ref_header["CTYPE2"] = "DEC--TAN"
ref_header["CRVAL1"] = ra_center
ref_header["CRVAL2"] = dec_center
ref_header["CRPIX1"] = COMMON_SIZE[1] / 2.0
ref_header["CRPIX2"] = COMMON_SIZE[0] / 2.0
ref_header["CDELT1"] = -pixel_scale_deg
ref_header["CDELT2"] = pixel_scale_deg

common_wcs = WCS(ref_header)
ast_x_ref, ast_y_ref = common_wcs.all_world2pix(ra_measured, dec_measured, 0)

# -------------------------------------------------------------------------
# 5. Reproject & Contrast-Normalize Frames
# -------------------------------------------------------------------------
print("Reprojecting all frames onto a single stationary star field...")
reprojected_images = []

for idx, (f, w_in) in enumerate(zip(files, wcs_list)):
    with fits.open(f) as hdul:
        data = hdul[0].data.astype(np.float32)

    # Reproject image to common reference canvas
    aligned, footprint = reproject_interp((data, w_in), common_wcs, shape_out=COMMON_SIZE)

    # Mask padding borders and stretch sky cleanly
    valid_mask = footprint > 0.5
    valid_pixels = aligned[valid_mask]

    interval = ZScaleInterval(contrast=0.08)
    vmin, vmax = interval.get_limits(valid_pixels)

    norm = ImageNormalize(vmin=vmin, vmax=vmax, stretch=LinearStretch(), clip=True)
    scaled_frame = norm(aligned)
    scaled_frame[~valid_mask] = 0.0

    reprojected_images.append(scaled_frame)
    print(f"[{idx+1:02d}/{len(files)}] Aligned {f}")

reprojected_images = np.array(reprojected_images)

# -------------------------------------------------------------------------
# 6. Render Animation
# -------------------------------------------------------------------------
fig, ax = plt.subplots(figsize=(9, 9), facecolor="black")
plt.subplots_adjust(left=0.02, right=0.98, bottom=0.08, top=0.92)

img_display = ax.imshow(reprojected_images[0], cmap="gray", origin="lower", vmin=0, vmax=1)

(curr_marker,) = ax.plot([], [], "ro", markersize=7, fillstyle="none", markeredgewidth=1.8, label="2005 QN173")
(trail_line,) = ax.plot([], [], "cyan", lw=1.2, alpha=0.65, ls="--", label="Observed Path")
past_points = ax.scatter([], [], c="cyan", s=18, alpha=0.5, edgecolors="none")

title_text = ax.text(
    0.03, 0.95, "",
    transform=ax.transAxes,
    color="yellow",
    fontsize=11,
    weight="bold",
    bbox=dict(boxstyle="round,pad=0.4", fc="black", ec="yellow", alpha=0.7)
)

progress_text = ax.text(
    0.03, 0.89, "",
    transform=ax.transAxes,
    color="white",
    fontsize=9,
    bbox=dict(boxstyle="round,pad=0.3", fc="black", ec="gray", alpha=0.5)
)

# Tight crop centered around the traversed orbital track
margin = 120
ax.set_xlim(ast_x_ref.min() - margin, ast_x_ref.max() + margin)
ax.set_ylim(ast_y_ref.min() - margin, ast_y_ref.max() + margin)
ax.axis("off")
ax.legend(loc="upper right", facecolor="black", labelcolor="white", framealpha=0.6, fontsize=9)

total_days = jds[-1] - jds[0]

def update(i):
    img_display.set_data(reprojected_images[i])
    cx, cy = ast_x_ref[i], ast_y_ref[i]
    curr_marker.set_data([cx], [cy])
    trail_line.set_data(ast_x_ref[: i + 1], ast_y_ref[: i + 1])
    past_points.set_offsets(np.column_stack([ast_x_ref[:i], ast_y_ref[:i]]))

    elapsed = jds[i] - jds[0]
    t_str = t_mid_isot[i][:16].replace("T", " ")
    title_text.set_text(f"UTC: {t_str}  (Frame {i+1}/{len(files)})")
    progress_text.set_text(
        f"Day +{elapsed:.2f} of {total_days:.1f} days  |  RA: {ra_measured[i]:.4f}°, Dec: {dec_measured[i]:.4f}°"
    )
    return img_display, curr_marker, trail_line, past_points, title_text, progress_text

ani = animation.FuncAnimation(fig, update, frames=len(files), interval=800, blit=False, repeat=True)
ani.save("asteroid_from_fits_only.gif", writer="pillow", fps=1.2, dpi=130)
plt.close(fig)

